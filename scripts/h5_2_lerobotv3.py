    parser.add_argument("--task-name", default="insert_usb")
    parser.add_argument("--source-format", choices=("auto", "libero", "generic"), default="auto")
    parser.add_argument("--fps", type=float, default=None, help="State frequency (default: source control_freq, else 50 Hz)")
    parser.add_argument("--camera-fps", type=float, default=None, help="Source camera frequency (default: LIBERO state frequency, else 25 Hz)")
    parser.add_argument("--image-size", nargs=2, type=int, metavar=("HEIGHT", "WIDTH"),
                        help="Resize both cameras before writing, e.g. --image-size 192 256")
    parser.add_argument("--robot-dofs", type=int, default=7)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--max-episodes", type=int, default=None)
    parser.add_argument("--episode-start", type=int, default=0)
    parser.add_argument("--allow-vector-truncate", action="store_true",
                        help="Take the first robot-dofs values from larger vectors, e.g. full MuJoCo qfrc_inverse.")
    parser.add_argument("--allow-missing-wrench", action="store_true")
    parser.add_argument("--joint-key", default=None)
    parser.add_argument("--velocity-key", default=None)
    parser.add_argument("--q-cmd-key", default=None)
    parser.add_argument("--delta-q-key", default=None)
    parser.add_argument("--torque-key", default=None)
    parser.add_argument("--tau-free-key", default=None)
    parser.add_argument("--tau-ext-key", default=None)
    parser.add_argument("--tau-ext-raw-key", default=None)
    parser.add_argument("--wrench-key", default=None)
    parser.add_argument("--wrench-raw-key", default=None)
    parser.add_argument("--ee-pose-key", default=None)
    parser.add_argument("--action-key", default=None)
    parser.add_argument("--state-timestamp-key", default=None)
    parser.add_argument("--camera-timestamp-key", default=None)
    parser.add_argument("--wrist-key", default=None)
    parser.add_argument("--side-key", default=None)

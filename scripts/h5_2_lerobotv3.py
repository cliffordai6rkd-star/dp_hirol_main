def _natural_key(value: str) -> Tuple[int, Any]:
    match = re.search(r"(\d+)(?!.*\d)", str(value))
    return (0, int(match.group(1))) if match else (1, str(value))


def _normalise_key(value: str) -> str:
    return str(value).strip().strip("/")


def _read_nested(container: Any, key: str) -> np.ndarray:
    obj = container
    for part in _normalise_key(key).split("/"):
        if part:
            obj = obj[part]
    if isinstance(obj, h5py.Dataset):
        return np.asarray(obj[()])
    return np.asarray(obj)


def _try_read(container: Any, keys: Sequence[str]) -> Tuple[Optional[np.ndarray], Optional[str]]:
    for key in keys:
        if not key:
            continue
        try:
            return _read_nested(container, key), key
        except (KeyError, IndexError, TypeError, ValueError):
            pass
    return None, None


def _episode_sources(paths: Sequence[Path]) -> List[EpisodeSource]:
    sources: List[EpisodeSource] = []
    next_index = 0
    for path in paths:
        with h5py.File(path, "r") as file:
            if "data" in file and isinstance(file["data"], h5py.Group):
                base = file["data"]
                candidates = [name for name, obj in base.items() if isinstance(obj, h5py.Group)]
                if not candidates:
                    sources.append(EpisodeSource(path, "data", next_index))
                    next_index += 1
                    continue
            else:
                # A standalone episode may contain nested ``obs`` and
                # ``cameras`` groups at the root.  Only treat root groups as
                # episodes when their names explicitly say demo/episode.
                candidates = [
                    name for name, obj in file.items()
                    if isinstance(obj, h5py.Group)
                    and re.match(r"(?:demo|episode)[_-]?\d+$", name, re.IGNORECASE)
                ]
                base = file
            candidates = sorted(candidates, key=_natural_key)
            # A file containing direct frame datasets is treated as one episode.
            if not candidates:
                sources.append(EpisodeSource(path, "", next_index))
                next_index += 1
                continue
            for name in candidates:
                if not isinstance(base[name], h5py.Group):
                    continue
                match = re.search(r"(\d+)(?!.*\d)", str(name))
                index = int(match.group(1)) if match else next_index
                sources.append(EpisodeSource(path, f"data/{name}" if "data" in file else name, index))
                next_index = max(next_index + 1, index + 1)
    return sources


def _resolve_inputs(values: Sequence[str]) -> List[Path]:
    paths: List[Path] = []
    for value in values:
        path = Path(value).expanduser()
        matches = [Path(item) for item in glob.glob(str(path))]
        if path.is_dir():
            matches = sorted(path.glob("*.h5")) + sorted(path.glob("*.hdf5"))
        if not matches and path.is_file():
            matches = [path]
        paths.extend(matches)
    unique = sorted({item.resolve() for item in paths})
    if not unique:
        raise FileNotFoundError(f"No HDF5 files matched: {list(values)}")
    return unique


def _group_for_source(file: h5py.File, source: EpisodeSource) -> h5py.Group:
    if source.group_name:
        return file[source.group_name]
    return file


def _resolve_source_settings(sources: Sequence[EpisodeSource], args: argparse.Namespace) -> None:
    libero_flags, frequencies = [], []
    for source in sources:
        with h5py.File(source.path, "r") as file:
            group = _group_for_source(file, source)
            libero_flags.append(all(key in group for key in ("obs/joint_states", "actions", "states")))
            attrs = file["data"].attrs if "data" in file else file.attrs
            raw = attrs.get("env_args", "{}")
            if isinstance(raw, bytes):
                raw = raw.decode("utf-8")
            env_args = json.loads(raw) if isinstance(raw, str) else dict(raw)
            frequency = env_args.get("env_kwargs", {}).get("control_freq")
            if frequency is not None:
                frequencies.append(float(frequency))
    if args.source_format == "auto":
        if any(libero_flags) and not all(libero_flags):
            raise ValueError("Convert LIBERO and generic robot logs separately.")
        args.source_format = "libero" if all(libero_flags) else "generic"
    unique_frequencies = sorted(set(frequencies))
    if len(unique_frequencies) > 1:
        raise ValueError(f"Source control frequencies differ: {unique_frequencies}")
    source_fps = unique_frequencies[0] if unique_frequencies else None
    if args.fps is None:
        if args.source_format == "libero" and source_fps is None:
            raise ValueError("LIBERO control_freq is missing; pass its actual --fps.")
        args.fps = source_fps if source_fps is not None else 50.0
    if args.source_format == "libero" and source_fps is not None and not np.isclose(args.fps, source_fps):
        raise ValueError(
            f"LIBERO source is {source_fps:g} Hz, but --fps is {args.fps:g}. "
            "This converter does not resample state/action streams."
        )
    if args.camera_fps is None:
        args.camera_fps = args.fps if args.source_format == "libero" else 25.0
    if args.fps <= 0 or args.camera_fps <= 0:
        raise ValueError("--fps and --camera-fps must be positive")
    if not np.isclose(args.fps, round(args.fps)):
        raise ValueError("The LeRobot writer requires an integer state frequency.")


def _as_time_major(value: np.ndarray, name: str) -> np.ndarray:
    value = np.asarray(value)
    if value.ndim == 1:
        return value[:, None]
    if value.ndim != 2:
        raise ValueError(f"{name} must be 1-D or 2-D with time first, got {value.shape}")
    return value


def _fit_vector(value: np.ndarray, length: int, dim: int, name: str, allow_truncate: bool) -> np.ndarray:
    value = _as_time_major(value, name)
    if value.shape[0] != length:
        raise ValueError(f"{name} has {value.shape[0]} rows; expected {length}")
    if value.shape[1] == dim:
        return np.asarray(value, dtype=np.float32)
    if allow_truncate and value.shape[1] >= dim:
        return np.asarray(value[:, :dim], dtype=np.float32)
    raise ValueError(
        f"{name} has shape {value.shape}; expected (*,{dim}). "
        "Pass the correct --*-key or use --allow-vector-truncate for a larger state vector."
    )


def _finite_difference(values: np.ndarray, dt: float) -> np.ndarray:
    if values.shape[0] <= 1:
        return np.zeros_like(values, dtype=np.float32)
    return np.gradient(values.astype(np.float64), dt, axis=0, edge_order=1).astype(np.float32)


def _rotvec_to_quat(rotvec: np.ndarray) -> np.ndarray:
    theta = np.linalg.norm(rotvec, axis=1, keepdims=True)
    half = 0.5 * theta
    scale = 0.5 * np.sinc(theta / (2.0 * np.pi))
    xyz = rotvec * scale
    return np.concatenate([xyz, np.cos(half)], axis=1).astype(np.float32)


def _ee_pose(value: np.ndarray, length: int, name: str, allow_truncate: bool) -> np.ndarray:
    value = _as_time_major(value, name)
    if value.shape[0] != length:
        raise ValueError(f"{name} has {value.shape[0]} rows; expected {length}")
    if value.shape[1] == 7:
        return value.astype(np.float32)
    if value.shape[1] == 6:
        return np.concatenate(
            [value[:, :3].astype(np.float32), _rotvec_to_quat(value[:, 3:6])], axis=1
        ).astype(np.float32)
    # LIBERO robot_states is [gripper(2), ee_position(3), ee_quaternion(4)].
    if value.shape[1] >= 9 and ("robot" in name.lower() or "state" in name.lower()):
        return value[:, 2:9].astype(np.float32)
    if allow_truncate and value.shape[1] >= 7:
        return value[:, :7].astype(np.float32)
    raise ValueError(
        f"{name} has shape {value.shape}; expected ee pose (*,7), pose+rotvec (*,6), "
        "or LIBERO robot_states (*,>=9)."
    )


def _image_array(value: np.ndarray, name: str) -> np.ndarray:
    value = np.asarray(value)
    if value.ndim != 4:
        raise ValueError(f"{name} must have shape (T,H,W,C) or (T,C,H,W), got {value.shape}")
    if value.shape[-1] in (1, 3, 4):
        result = value
    elif value.shape[1] in (1, 3, 4):
        result = np.transpose(value, (0, 2, 3, 1))
    else:
        raise ValueError(f"{name} does not look like an RGB image array: {value.shape}")
    if result.shape[-1] == 1:
        result = np.repeat(result, 3, axis=-1)
    elif result.shape[-1] == 4:
        result = result[..., :3]
    if result.dtype != np.uint8:
        if np.issubdtype(result.dtype, np.floating) and np.nanmax(result) <= 1.0:
            result = result * 255.0
        result = np.clip(result, 0, 255).astype(np.uint8)
    return np.ascontiguousarray(result)


def _resize_images(images: np.ndarray, height: Optional[int], width: Optional[int]) -> np.ndarray:
    if height is None and width is None:
        return images
    if height is None or width is None or height <= 0 or width <= 0:
        raise ValueError("--image-size requires two positive integers: HEIGHT WIDTH")
    if images.shape[1:3] == (height, width):
        return images
    return np.stack(
        [np.asarray(Image.fromarray(frame).resize((width, height), Image.Resampling.BILINEAR)) for frame in images],
        axis=0,
    ).astype(np.uint8, copy=False)


def _align_images(images: np.ndarray, length: int) -> Tuple[np.ndarray, np.ndarray]:
    if images.shape[0] == length:
        indices = np.arange(length, dtype=np.int64)
    elif images.shape[0] < length:
        # Previous-frame hold on a slower camera timeline, e.g. 25 Hz -> 50 Hz.
        indices = np.floor(np.arange(length, dtype=np.float64) * images.shape[0] / length).astype(np.int64)
        indices = np.clip(indices, 0, images.shape[0] - 1)
    else:
        indices = np.floor(np.arange(length, dtype=np.float64) * images.shape[0] / length).astype(np.int64)
        indices = np.clip(indices, 0, images.shape[0] - 1)
    return images[indices], indices


def _timestamp_ns(value: Optional[np.ndarray], length: int, fps: float, name: str,
                  unit: Optional[str] = None) -> np.ndarray:
    if value is None:
        return np.rint(np.arange(length, dtype=np.float64) * 1e9 / fps).astype(np.int64)
    values = np.asarray(value).reshape(-1)
    if values.shape[0] != length:
        raise ValueError(f"{name} has {values.shape[0]} rows; expected {length}")
    values = values.astype(np.float64)
    finite = np.isfinite(values)
    if not np.all(finite):
        raise ValueError(f"{name} contains non-finite timestamps")
    # Values below 1e12 are conventionally seconds or milliseconds. Absolute
    # nanosecond timestamps are already around 1e18.
    scale = {"ns": 1.0, "s": 1e9}.get(unit)
    if scale is None:
        scale = 1e9 if np.max(np.abs(values)) < 1e6 else (1e6 if np.max(np.abs(values)) < 1e12 else 1.0)
    return np.rint(values * scale).astype(np.int64)


def _key_candidates(explicit: Optional[str], aliases: Sequence[str]) -> List[str]:
    return ([explicit] if explicit else []) + list(aliases)


def _load_episode(group: h5py.Group, args: argparse.Namespace) -> EpisodeArrays:
    # Joint positions define the primary state length.
    joint_raw, _ = _try_read(group, _key_candidates(args.joint_key, (
        "observation/joint", "joint", "q", "qpos", "obs/joint_states", "joint_states",
    )))
    if joint_raw is None:
        raise KeyError("Could not find joint positions. Pass --joint-key.")
    joint_raw = _as_time_major(joint_raw, "joint")
    length = joint_raw.shape[0]
    joint = _fit_vector(joint_raw, length, args.robot_dofs, "joint", args.allow_vector_truncate)
    dt = 1.0 / args.fps

    action_raw, _ = _try_read(group, _key_candidates(args.action_key, (
        "action", "actions", "q_cmd", "command", "commands", "obs/action",
    )))
    if action_raw is None:
        action = joint.copy()
    else:
        action = _fit_vector(action_raw, length, args.robot_dofs, "action", args.allow_vector_truncate)

    q_cmd_raw, _ = _try_read(group, _key_candidates(args.q_cmd_key, (
        "observation/q_cmd", "q_cmd", "commanded_joint", "commanded_q", "obs/q_cmd",
    )))
    q_cmd = action.copy() if q_cmd_raw is None else _fit_vector(
        q_cmd_raw, length, args.robot_dofs, "q_cmd", args.allow_vector_truncate
    )
    delta_raw, _ = _try_read(group, _key_candidates(args.delta_q_key, (
        "observation/delta_q", "delta_q", "dq_cmd", "obs/delta_q",
    )))
    delta_q = q_cmd - joint if delta_raw is None else _fit_vector(
        delta_raw, length, args.robot_dofs, "delta_q", args.allow_vector_truncate
    )

    velocity_raw, _ = _try_read(group, _key_candidates(args.velocity_key, (
        "observation/velocity", "velocity", "dq", "qvel", "obs/dq", "obs/joint_vel",
    )))
    velocity = _finite_difference(joint, dt) if velocity_raw is None else _fit_vector(
        velocity_raw, length, args.robot_dofs, "velocity", args.allow_vector_truncate
    )

    torque_raw, _ = _try_read(group, _key_candidates(args.torque_key, (
        "observation/torque", "torque", "tau", "obs/tau", "obs/torque",
    )))
    if args.source_format == "libero":
        torque_raw = None
    torque = np.zeros((length, args.robot_dofs), dtype=np.float32) if torque_raw is None else _fit_vector(
        torque_raw, length, args.robot_dofs, "torque", args.allow_vector_truncate
    )
    tau_free_raw, _ = _try_read(group, _key_candidates(args.tau_free_key, (
        "observation/tau_free", "tau_free", "obs/tau_free",
    )))
    tau_free = torque.copy() if tau_free_raw is None else _fit_vector(
        tau_free_raw, length, args.robot_dofs, "tau_free", args.allow_vector_truncate
    )
    tau_ext_raw_value, _ = _try_read(group, _key_candidates(args.tau_ext_key, (
        "observation/tau_ext", "tau_ext", "external_torque", "obs/tau_ext",
    )))
    tau_ext = torque - tau_free if tau_ext_raw_value is None else _fit_vector(
        tau_ext_raw_value, length, args.robot_dofs, "tau_ext", args.allow_vector_truncate
    )
    tau_ext_raw_value, _ = _try_read(group, _key_candidates(args.tau_ext_raw_key, (
        "observation/tau_ext_raw", "tau_ext_raw", "obs/tau_ext_raw",
    )))
    tau_ext_raw = tau_ext.copy() if tau_ext_raw_value is None else _fit_vector(
        tau_ext_raw_value, length, args.robot_dofs, "tau_ext_raw", args.allow_vector_truncate
    )

    wrench_raw_value, wrench_key = _try_read(group, _key_candidates(args.wrench_key, (
        "observation/wrench", "wrench", "wrenches", "obs/wrenches", "obs/wrench", "wrench_ee",
    )))
    if wrench_raw_value is None:
        if not args.allow_missing_wrench:
            raise KeyError("Could not find wrench data. Pass --wrench-key or --allow-missing-wrench.")
        wrench = np.zeros((length, 6), dtype=np.float32)
        wrench_key = "derived:zeros"
    else:
        wrench = _fit_vector(wrench_raw_value, length, 6, "wrench", args.allow_vector_truncate)
    wrench_raw_value, wrench_raw_key = _try_read(group, _key_candidates(args.wrench_raw_key, (
        "observation/wrench_raw", "wrench_raw", "wrenches_raw", "obs/wrenches_raw",
    )))
    wrench_raw = wrench.copy() if wrench_raw_value is None else _fit_vector(
        wrench_raw_value, length, 6, "wrench_raw", args.allow_vector_truncate
    )

    pose_raw, pose_key = _try_read(group, _key_candidates(args.ee_pose_key, (
        "observation/ee_pose", "ee_pose", "ee_states", "obs/ee_states", "robot_states",
    )))
    if pose_raw is None:
        raise KeyError("Could not find end-effector pose. Pass --ee-pose-key.")
    ee_pose = _ee_pose(pose_raw, length, pose_key or "ee_pose", args.allow_vector_truncate)

    state_time_raw, state_time_key = _try_read(group, _key_candidates(args.state_timestamp_key, (
        "timing/state_timestamp_ns", "state_timestamp_ns", "timestamp_ns", "timestamps", "time", "timestamp",
    )))
    state_time_unit = "ns" if state_time_key and state_time_key.endswith("_ns") else None
    if state_time_raw is None and args.source_format == "libero":
        states = np.asarray(group["states"])
        state_time_raw, state_time_unit = states[:, 0], "s"
    state_timestamp_ns = _timestamp_ns(state_time_raw, length, args.fps, "state timestamp", state_time_unit)
    if length > 1 and not np.allclose(np.diff(state_timestamp_ns) / 1e9, dt, atol=1e-5, rtol=0):
        raise ValueError("Source timestamps do not match --fps; resample explicitly before conversion.")
    # Timestamp may be recorded in another absolute epoch. Keep the relative
    # time column centered at the first sample while retaining absolute ns for
    # camera alignment.
    timestamp = (state_timestamp_ns - state_timestamp_ns[0]).astype(np.float64) / 1e9

    wrist_raw, wrist_key = _try_read(group, _key_candidates(args.wrist_key, (
        "observation/images/wrist", "images/wrist", "wrist", "wrist_rgb",
        "obs/eye_in_hand_rgb", "eye_in_hand_rgb", "obs/wrist_rgb",
    )))
    side_raw, side_key = _try_read(group, _key_candidates(args.side_key, (
        "observation/images/side", "images/side", "side", "side_rgb",
        "obs/agentview_rgb", "agentview_rgb", "obs/side_rgb",
    )))
    if wrist_raw is None or side_raw is None:
        missing = ["wrist" if wrist_raw is None else "", "side" if side_raw is None else ""]
        raise KeyError(f"Could not find camera data ({', '.join(x for x in missing if x)}). Pass --wrist-key/--side-key.")
    wrist = _image_array(wrist_raw, wrist_key or "wrist")
    side = _image_array(side_raw, side_key or "side")
    wrist = _resize_images(wrist, args.image_height, args.image_width)
    side = _resize_images(side, args.image_height, args.image_width)
    wrist_images, wrist_indices = _align_images(wrist, length)
    side_images, _ = _align_images(side, length)
    if wrist_images.shape[1:] != side_images.shape[1:]:
        raise ValueError(
            f"Wrist and side image shapes differ after alignment: {wrist_images.shape[1:]} vs {side_images.shape[1:]}. "
            "Resize them before conversion or pass --image-size HEIGHT WIDTH."
        )

    camera_time_raw, _ = _try_read(group, _key_candidates(args.camera_timestamp_key, (
        "timing/camera_timestamp_ns", "camera_timestamp_ns", "image_timestamp_ns", "camera_timestamps_ns",
    )))
    if camera_time_raw is None:
        camera_timestamp_ns = state_timestamp_ns.copy()
    else:
        camera_values = np.asarray(camera_time_raw).reshape(-1)
        # A camera timestamp may be per-camera-frame rather than per-state-row.
        if camera_values.shape[0] == wrist.shape[0]:
            camera_timestamp_ns = _timestamp_ns(camera_values, wrist.shape[0], args.camera_fps, "camera timestamp", "ns")[wrist_indices]
        elif camera_values.shape[0] == length:
            camera_timestamp_ns = _timestamp_ns(camera_values, length, args.fps, "camera timestamp", "ns")
        else:
            raise ValueError(
                f"Camera timestamps have {camera_values.shape[0]} rows; expected {wrist.shape[0]} or {length}."
            )
    # If no camera timestamps were supplied, approximate the held-frame capture
    # time from the state timeline and camera index.
    if camera_time_raw is None and wrist.shape[0] < length:
        camera_timestamp_ns = state_timestamp_ns[0] + np.rint(
            wrist_indices * 1e9 / args.camera_fps
        ).astype(np.int64)
        camera_timestamp_ns = np.minimum(camera_timestamp_ns, state_timestamp_ns)
    camera_age_s = (state_timestamp_ns - camera_timestamp_ns).astype(np.float64) / 1e9
    camera_valid = (camera_timestamp_ns <= state_timestamp_ns).astype(np.uint8)

    return EpisodeArrays(
        joint=joint, velocity=velocity, q_cmd=q_cmd, delta_q=delta_q,
        torque=torque, tau_free=tau_free, tau_ext=tau_ext, tau_ext_raw=tau_ext_raw,
        wrench=wrench, wrench_raw=wrench_raw, ee_pose=ee_pose, action=action,
        state_timestamp_ns=state_timestamp_ns, camera_timestamp_ns=camera_timestamp_ns,
        camera_index=wrist_indices.astype(np.int64), camera_age_s=camera_age_s.astype(np.float32),
        camera_valid=camera_valid, wrist_images=wrist_images, side_images=side_images,
        timestamp=timestamp.astype(np.float32),
    )


def _feature_specs(wrist_images: np.ndarray, side_images: np.ndarray,
                   fps: float = 50.0, source_format: str = "generic") -> Mapping[str, Mapping[str, Any]]:
    features = {
        key: dict(value) for key, value in FEATURES.items()
        if source_format != "libero" or key not in LIBERO_UNAVAILABLE_FEATURES
    }
    for key, images in (
        ("observation.images.wrist", wrist_images),
        ("observation.images.side", side_images),
    ):
        height, width, channels = images.shape[1:]
        features[key] = {
            "dtype": "video",
            "shape": (int(height), int(width), int(channels)),
            "info": {
                "video.height": int(height),
                "video.width": int(width),
                "video.codec": "av1",
                "video.pix_fmt": "yuv420p",
                "video.is_depth_map": False,
                "video.fps": int(round(fps)),
                "video.channels": int(channels),
                "has_audio": False,
            },
        }
    return features


def _frame_arrays(arrays: EpisodeArrays) -> Iterable[Mapping[str, Any]]:
    length = arrays.joint.shape[0]
    names = (
        "joint", "velocity", "q_cmd", "delta_q", "torque", "tau_free", "tau_ext",
        "tau_ext_raw", "wrench", "wrench_raw", "ee_pose", "action",
    )
    values = [getattr(arrays, name) for name in names]
    for index in range(length):
        frame: dict[str, Any] = {
            **{f"observation.{name}": value[index] for name, value in zip(names, values) if name != "action"},
            "action": arrays.action[index],
            # Fixed-shape scalar features are represented as `(1,)` arrays;
            # this is required by LeRobot's frame validator.
            "timing.state_timestamp_ns": np.asarray(
                [arrays.state_timestamp_ns[index]], dtype=np.int64
            ),
            "timing.camera_timestamp_ns": np.asarray(
                [arrays.camera_timestamp_ns[index]], dtype=np.int64
            ),
            "timing.camera_index": np.asarray([arrays.camera_index[index]], dtype=np.int64),
            "timing.camera_age_s": np.asarray([arrays.camera_age_s[index]], dtype=np.float32),
            "timing.camera_valid": np.asarray([arrays.camera_valid[index]], dtype=np.uint8),
            "observation.images.wrist": arrays.wrist_images[index],
            "observation.images.side": arrays.side_images[index],
            "timestamp": arrays.timestamp[index],
        }
        yield frame


def _write_conversion_metadata(
    output: Path,
    sources: Sequence[EpisodeSource],
    args: argparse.Namespace,
    episode_summaries: Sequence[Mapping[str, Any]],
) -> None:
    metadata = {
        "format": "lerobot_v3",
        "source_format": args.source_format,
        "task": args.task_name,
        "fps": args.fps,
        "camera_nominal_fps": args.camera_fps,
        "image_size": None if args.image_size is None else [args.image_height, args.image_width],
        "camera_storage": "previous_camera_frame_held_on_state_rows",
        "camera_align": "previous",
        "ee_pose_format": "xyz+xyzw",
        "omitted_features": sorted(LIBERO_UNAVAILABLE_FEATURES) if args.source_format == "libero" else [],
        "action_semantics": "OSC_POSE deltas + gripper" if args.source_format == "libero" else "source action",
        "state_timestamp_source": "states[:,0] seconds" if args.source_format == "libero" and not args.state_timestamp_key else args.state_timestamp_key,
        "source_files": [str(source.path) for source in sources],
        "source_groups": [source.group_name for source in sources],
        "episodes": list(episode_summaries),
        "mapping": {
            "joint": args.joint_key,
            "velocity": args.velocity_key,
            "q_cmd": args.q_cmd_key,
            "delta_q": args.delta_q_key,
            "torque": args.torque_key,
            "tau_free": args.tau_free_key,
            "tau_ext": args.tau_ext_key,
            "tau_ext_raw": args.tau_ext_raw_key,
            "wrench": args.wrench_key,
            "wrench_raw": args.wrench_raw_key,
            "ee_pose": args.ee_pose_key,
            "action": args.action_key,
            "wrist": args.wrist_key,
            "side": args.side_key,
        },
    }
    (output / "meta" / "wrench_conversion.json").write_text(
        json.dumps(metadata, indent=2, ensure_ascii=False), encoding="utf-8"
    )



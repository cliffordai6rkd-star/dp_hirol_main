def main() -> None:
    args = _parse_args()
    if args.robot_dofs <= 0:
        raise ValueError("--robot-dofs must be positive")
    args.image_height, args.image_width = (args.image_size if args.image_size else (None, None))
    if args.episode_start < 0:
        raise ValueError("--episode-start must be non-negative")
    inputs = _resolve_inputs(args.input)
    sources = _episode_sources(inputs)
    sources = sources[args.episode_start:]
    if args.max_episodes is not None:
        sources = sources[:args.max_episodes]
    if not sources:
        raise ValueError("No episodes selected")
    _resolve_source_settings(sources, args)
    output = args.output.expanduser().resolve()
    if output.exists():
        if not args.overwrite:
            raise FileExistsError(f"Output exists: {output}. Pass --overwrite to replace it.")
        shutil.rmtree(output)
    output.parent.mkdir(parents=True, exist_ok=True)

    try:
        from diffusion_policy.common.lerobot_v3_io import LeRobotV3Writer
    except ImportError as exc:
        raise RuntimeError(
            "Run this script from dp_hirol_main and install the LeRobot v3 stack "
            "(`lerobot==0.4.0`, pyarrow, h5py)."
        ) from exc

    writer = None
    total_frames = 0
    episode_summaries = []
    try:
        for output_index, source in enumerate(sources):
            with h5py.File(source.path, "r") as file:
                arrays = _load_episode(_group_for_source(file, source), args)
            if writer is None:
                features = _feature_specs(arrays.wrist_images, arrays.side_images, args.fps, args.source_format)
                writer = LeRobotV3Writer(
                    root=str(output), fps=int(round(args.fps)), features=features,
                    video_keys=("observation.images.wrist", "observation.images.side"),
                    robot_type="panda" if args.source_format == "libero" else "unknown",
                    codec="av1", repo_id=output.name,
                )
            for frame in _frame_arrays(arrays):
                writer.add_frame(frame)
            writer.save_episode(task=args.task_name)
            length = int(arrays.joint.shape[0])
            total_frames += length
            episode_summaries.append({
                "episode_index": output_index,
                "source": str(source.path),
                "source_group": source.group_name,
                "frames": length,
            })
            print(f"[{output_index + 1}/{len(sources)}] {source.path.name}:{source.group_name or '<root>'} -> {length} frames")
        assert writer is not None
        writer.finalize()
    except Exception:
        # LeRobot may leave a partial directory. Keeping it helps debugging;
        # the next run can remove it with --overwrite.
        raise

    _write_conversion_metadata(output, sources, args, episode_summaries)
    print(f"Wrote {len(sources)} episodes / {total_frames} frames to {output}")
    print("Conversion complete. Set dataset_path in a training config matching the exported features and FPS.")


if __name__ == "__main__":
    main()

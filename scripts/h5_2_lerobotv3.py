#!/usr/bin/env python3
"""Convert episode HDF5 files to the LeRobot v3 dataset used by DP-HiRoL.

The converter writes the same kind of directory as
``data/insert_usb_50hz_lerobot_v3``:

    output/
      data/chunk-*/file-*.parquet
      meta/info.json, stats.json, tasks.parquet
      meta/episodes/chunk-*/file-*.parquet
      videos/observation.images.wrist/chunk-*/file-*.mp4
      videos/observation.images.side/chunk-*/file-*.mp4

It accepts either one HDF5 containing ``data/demo_N`` groups (LIBERO style),
one HDF5 containing ``episode_N`` groups, or a directory/glob of one-episode
HDF5 files. Source keys can be overridden when a robot logger uses different
names. Missing derived quantities are computed from the joint/action streams.

Example for a LIBERO-FT HDF5::

    python scripts/h5_2_lerobotv3.py \
      --input /path/to/task_demo_wrench.hdf5 \
      --output data/libero_task_lerobot_v3 \
      --task-name open_top_drawer_put_bowl \
      --fps 20 --camera-fps 20 --overwrite

Example for real-robot HDF5 files::

    python scripts/h5_2_lerobotv3.py \
      --input '/path/to/raw/*.h5' \
      --output data/insert_usb_50hz_lerobot_v3 \
      --task-name insert_usb --fps 50 --camera-fps 25 \
      --joint-key observation/joint --action-key action \
      --wrist-key cameras/wrist --side-key cameras/side \
      --wrench-key wrench --torque-key torque --overwrite

The output values are stored in physical units. The script does not normalize
features; ``meta/stats.json`` is generated by LeRobot and DP-HiRoL normalizes
the selected fields at training time.
"""

